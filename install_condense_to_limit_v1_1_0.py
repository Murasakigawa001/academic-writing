    print("     其他 Agent：把该目录放进技能根目录，确保 SKILL.md 在根部")

    if a.register:
        exe = shutil.which("ima_skill_create")
        if not exe:
            print("\n未找到 ima_skill_create，跳过注册。")
            return 0
        print("\n注册中…")
        return subprocess.call([exe, "-d", dest])

    return 1 if bad else 0


