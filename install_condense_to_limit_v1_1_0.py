def main():
    ap = argparse.ArgumentParser(description="安装 condense-to-limit 技能 v" + VERSION)
    ap.add_argument("--target", default=".", help="安装到的父目录（默认当前目录）")
    ap.add_argument("--force", action="store_true", help="目标已存在时覆盖")
    ap.add_argument("--register", action="store_true", help="装好后调用 ima_skill_create 注册")
    ap.add_argument("--list", action="store_true", help="只列文件清单，不写盘")
    a = ap.parse_args()

    files = json.loads(base64.b64decode(PAYLOAD).decode())
    if a.list:
        print("condense-to-limit v%s，共 %d 个文件：" % (VERSION, len(files)))
        for k in sorted(files):
            print("  %-34s %6d bytes" % (k, len(base64.b64decode(files[k]))))
        return 0

    dest = os.path.join(os.path.abspath(os.path.expanduser(a.target)), "condense-to-limit")
    if os.path.exists(dest):
        if not a.force:
            print("目标已存在：%s\n加 --force 覆盖，或换一个 --target。" % dest)
            return 1
        shutil.rmtree(dest)

    ok, bad = 0, []
    for rel, b64 in files.items():
        path = os.path.join(dest, rel)
        os.makedirs(os.path.dirname(path) or dest, exist_ok=True)
        data = base64.b64decode(b64)
        with open(path, "wb") as fh:
            fh.write(data)
        want = next((f["sha256"] for f in MANIFEST["files"] if f["path"] == rel), None)
        got = hashlib.sha256(data).hexdigest()[:16]
        if want and got != want:
            bad.append(rel)
        ok += 1

    print("已安装 %d 个文件到：%s" % (ok, dest))
    print("校验：%s" % ("全部通过" if not bad else "以下文件哈希不符 → %s" % bad))

    sk = os.path.join(dest, "SKILL.md")
